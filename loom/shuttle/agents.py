"""Shuttle's sub-agents: one source (`shuttle/agents/<name>.md`), two targets (D-135).

A source file is front matter plus the role contract:

    ---
    name: scene-author
    description: one line the lead reads when it chooses a sub-agent
    model: sonnet                      # a Claude Code alias (sonnet, haiku, opus) or a full model id
    max_turns: 20                      # Claude Code stops the sub-agent after this many turns
    tool_calls: 60                     # loom-mcp refuses the owner token's calls past this
    phases: [P8]                       # where the lead may delegate it (rails)
    owns: scenes/{beat}.js             # what its owner token lets it write
    card: scene                        # optional: Relay's role card (loom/agents/roles/<card>.md) is appended
    tools: [get_beat, lab_snapshot, submit_scene]   # loom-mcp tools only; Claude Code sees mcp__loom__<tool>
    ---
    the Shuttle frame (owner token, what to return); with `card`, the generator appends Relay's shared rules and that
    card, so a Shuttle sub-agent and a Relay worker keep one contract (the frame wins where they differ)

`py -m loom shuttle agents --emit claude` writes `.claude/agents/shuttle-<name>.md` (subscription mode loads them from
the project); `--emit sdk` writes `shuttle/build/agents.json`, a map of Agent SDK `AgentDefinition` fields that
`claude --agents <file>` reads too (API mode). Both are generated: never edit them by hand.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from ..util import ENGINE_ROOT, LoomError

SOURCE = ENGINE_ROOT / "shuttle" / "agents"
CLAUDE_OUT = ENGINE_ROOT / ".claude" / "agents"
SDK_OUT = ENGINE_ROOT / "shuttle" / "build" / "agents.json"
PREFIX = "shuttle-"
MCP = "mcp__loom__"
CONFIG = ENGINE_ROOT / "loom" / "shuttle" / "config.json"


def model_id(name: str) -> str:
    """A Claude Code alias pinned to its full model id (config.json `model_ids`); a full id passes through."""
    from ..util import read_json
    ids = (read_json(CONFIG, {}) or {}).get("model_ids") or {}
    return ids.get(name, name) if isinstance(ids.get(name, name), str) else name


GENERATED = "<!-- generated by `py -m loom shuttle agents --emit claude` from shuttle/agents/{src}; do not edit by hand -->"
REQUIRED = ("name", "description", "model", "max_turns", "tool_calls", "phases", "tools")


def _value(v: str):
    v = v.strip()
    if v.startswith("[") and v.endswith("]"):
        return [x.strip().strip("\"'") for x in v[1:-1].split(",") if x.strip()]
    if re.fullmatch(r"-?\d+", v):
        return int(v)
    return v.strip("\"'")


def parse(path: Path) -> dict:
    text = Path(path).read_text(encoding="utf-8")
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", text, re.S)
    if not m:
        raise LoomError(f"{path}: no front matter")
    meta = {}
    for line in m.group(1).splitlines():
        if line.strip() and not line.lstrip().startswith("#"):
            k, _, v = line.partition(":")
            meta[k.strip()] = _value(v.split(" #", 1)[0])
    missing = [k for k in REQUIRED if k not in meta]
    if missing:
        raise LoomError(f"{path}: front matter misses {missing}")
    if isinstance(meta["phases"], str):
        meta["phases"] = [meta["phases"]]
    meta["prompt"] = m.group(2).strip() + "\n"
    meta["source"] = Path(path).name
    return meta


def load() -> dict[str, dict]:
    """Every sub-agent, by its short name (scene-author)."""
    out = {}
    for f in sorted(SOURCE.glob("*.md")):
        a = parse(f)
        out[a["name"]] = a
    return out


CARDS = ENGINE_ROOT / "loom" / "agents" / "roles"
CARD_NOTE = ("\n\n---\n\n# The shared rules and your role card (Relay's, the same contract)\nRead them with the frame above: where a card "
             "names a tool you do not have, or a conductor, the frame wins (the lead is your conductor; loom tools are your only "
             "tools; pass your owner token).\n\n")


def full_prompt(a: dict) -> str:
    """The sub-agent's system prompt: its Shuttle frame, then (with `card`) Relay's shared rules and role card."""
    if not a.get("card"):
        return a["prompt"]
    card = CARDS / f"{a['card']}.md"
    if not card.exists():
        raise LoomError(f"{a['source']}: no role card {card}")
    text = (a["prompt"].rstrip() + CARD_NOTE + (CARDS / "_shared.md").read_text(encoding="utf-8").strip() + "\n\n"
            + card.read_text(encoding="utf-8").strip() + "\n")
    from .. import toolbox as TB
    from ..agents.runtime import MENU_ROLES
    if a["card"] in MENU_ROLES and TB.enabled():
        # the same toolbox menu as Relay's scene, clip, kit and tweak roles (D-137); a beat's own tools are handed over in
        # its delegation context (conductor.task_message), and use_tool loads any other on request
        text += "\n## The toolbox (load a tool's section with use_tool)\n" + TB.menu() + "\n"
    return text


def resolve(name: str) -> dict | None:
    """A sub-agent by its short name or its emitted name (shuttle-scene-author)."""
    n = name.removeprefix(PREFIX)
    return load().get(n)


def claude_tools(a: dict) -> list[str]:
    return [MCP + t for t in a["tools"]]


def emit_claude(out_dir: Path = CLAUDE_OUT) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    names = set()
    for a in load().values():
        fm = ["---", f"name: {PREFIX}{a['name']}", f"description: {a['description']}", f"tools: {', '.join(claude_tools(a))}",
              f"model: {model_id(a['model'])}", f"maxTurns: {a['max_turns']}", "background: false"]
        if a.get("effort"):
            fm.append(f"effort: {a['effort']}")
        fm.append("---")
        body = "\n".join(fm) + "\n" + GENERATED.format(src=a["source"]) + "\n\n" + full_prompt(a)
        p = out_dir / f"{PREFIX}{a['name']}.md"
        p.write_text(body, encoding="utf-8")
        written.append(p)
        names.add(p.name)
    for old in out_dir.glob(f"{PREFIX}*.md"):      # a sub-agent removed from the source leaves no stale copy behind
        if old.name not in names:
            old.unlink()
    return written


def sdk_definitions() -> dict:
    """Agent SDK AgentDefinition fields (description, prompt, tools, model, maxTurns), keyed by the emitted name."""
    return {f"{PREFIX}{a['name']}": {"description": a["description"], "prompt": full_prompt(a), "tools": claude_tools(a), "model": model_id(a["model"]),
                                     "maxTurns": a["max_turns"], "background": False, **({"effort": a["effort"]} if a.get("effort") else {})}
            for a in load().values()}


def emit_sdk(out: Path = SDK_OUT) -> Path:
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(sdk_definitions(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return out


def read_claude(path: Path) -> dict:
    """The fields Claude Code reads from an emitted agent file (for the parity test)."""
    text = Path(path).read_text(encoding="utf-8")
    m = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n(.*)$", text, re.S)
    meta = {}
    for line in m.group(1).splitlines():
        k, _, v = line.partition(":")
        meta[k.strip()] = v.strip()
    meta["tools"] = [t.strip() for t in meta.get("tools", "").split(",") if t.strip()]
    meta["maxTurns"] = int(meta["maxTurns"]) if meta.get("maxTurns") else None
    return meta
