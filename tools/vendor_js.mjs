// Build the browser bundles Loom loads from libraries that ship only as ES modules (2026-10-08).
//   node tools/vendor_js.mjs        -> assets/vendor/js/*.js (GENERATED: rebuild, never hand-edit)
// Libraries that already ship a browser build (matter-js, p5.brush standalone) are loaded from node_modules directly.
import { build } from "esbuild";
import { writeFileSync } from "node:fs";
const out = "assets/vendor/js";
await build({
  entryPoints: ["node_modules/thinking-orbs/dist/engine.es.js"], bundle: true, format: "iife", globalName: "ThinkingOrbsEngine",
  outfile: `${out}/thinking_orbs_engine.js`, minify: false, legalComments: "inline",
  banner: { js: "/* GENERATED by tools/vendor_js.mjs from thinking-orbs 0.3.2 (MIT, Jakub Antalik). Do not edit. */" },
});
writeFileSync(`${out}/README.md`, "# Vendored browser bundles (GENERATED)\n\nBuilt by `node tools/vendor_js.mjs` from node_modules. Never hand-edit.\n\n| file | from | licence |\n|---|---|---|\n| thinking_orbs_engine.js | thinking-orbs 0.3.2 `engine` export | MIT (Jakub Antalik) |\n");
console.log("built", out);
